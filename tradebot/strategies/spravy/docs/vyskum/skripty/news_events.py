def _gdp() -> list[str]:
    """Jedno vydanie GDP za mesiac: koniec mesiaca (deň ≥ 20), štvrtok prednostne — bez revízií a iných publikácií."""
    by: dict[str, list[date]] = {}
    for s in GDP_RAW:
        d = date.fromisoformat(s)
        if d.day >= 20 or d.month in (12,) or d.year == 2026:
            by.setdefault(s[:7], []).append(d)
    out = []
    for _m, ds in by.items():
        thu = [d for d in ds if d.weekday() == 3]
        out.append((thu[-1] if thu else ds[-1]).isoformat())
    return sorted(out)


def _holidays(year: int) -> set[date]:
    """Celé sviatky (bez dní so skorým záverom)."""
    return {d for d, n in us_holidays(year).items() if "polovi" not in n.lower() and "skor" not in n.lower()}


def _business_days(year: int, month: int) -> list[date]:
    hol = _holidays(year)
    d = date(year, month, 1)
    out = []
    while d.month == month:
        if d.weekday() < 5 and d not in hol:
            out.append(d)
        d += timedelta(days=1)
    return out


def events() -> dict[str, list[datetime]]:
    def at(dates, hhmm):
        hh, mm = map(int, hhmm.split(":"))
        return sorted(datetime.combine(date.fromisoformat(d) if isinstance(d, str) else d, datetime.min.time())
                      + timedelta(hours=hh, minutes=mm) for d in dates)
    ism_m, ism_s = [], []
    for y in range(2021, 2027):
        for m in range(1, 13):
            if (y, m) > (2026, 10):
                break
            bd = _business_days(y, m)
            ism_m.append(bd[0])
            ism_s.append(bd[2])
    fomc = CAL["FOMC"]["dates"]
    minutes = [(date.fromisoformat(d) + timedelta(days=21)) for d in fomc]
    claims = []
    d = date(2021, 1, 7)
    hol = set().union(*(_holidays(y) for y in range(2021, 2027)))
    while d <= date(2026, 10, 29):
        claims.append(d - timedelta(days=1) if d in hol else d)
        d += timedelta(days=7)
    return {
        "FOMC": at(fomc, "14:00"), "CPI": at(CAL["CPI"]["dates"], "08:30"), "NFP": at(CAL["NFP"]["dates"], "08:30"),
        "PPI": at(PPI, "08:30"), "RETAIL": at(RETAIL, "08:30"), "PCE": at(PCE, "08:30"), "GDP": at(_gdp(), "08:30"),
        "JOLTS": at(JOLTS, "10:00"), "ISM_M": at(ism_m, "10:00"), "ISM_S": at(ism_s, "10:00"),
        "FOMC_MIN": at(minutes, "14:00"), "CLAIMS": at(claims, "08:30"),
    }


